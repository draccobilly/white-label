export type PortalCopy = typeof en;

type StringKeys<T> = { [K in keyof T]: T[K] extends string ? K : never }[keyof T];

/** The string-only part of the copy: what a client component may receive as props. */
export type PortalStrings = Pick<PortalCopy, StringKeys<PortalCopy>>;

export function portalCopy(locale: string | null | undefined): PortalCopy {
  return isSpanishLocale(locale) ? es : en;
}

export function portalStrings(copy: PortalCopy): PortalStrings {
  return Object.fromEntries(
    Object.entries(copy).filter(([, value]) => typeof value === "string"),
  ) as PortalStrings;
}

export function campaignStatusLabel(copy: PortalCopy, status: string) {
  switch (status) {
    case "ACTIVE":
      return copy.statusActive;
    case "PAUSED":
      return copy.statusPaused;
    case "COMPLETED":
      return copy.statusCompleted;
    default:
      return copy.statusDraft;
  }
}

export function requestStatusLabel(copy: PortalCopy, status: string | undefined) {
  if (status === "ANSWERED") return copy.requestAnswered;
  if (status === "RESOLVED") return copy.requestResolved;
  return copy.requestOpen;
}

export function payoutStatusLabel(copy: PortalCopy, status: string) {
  switch (status) {
    case "APPROVED":
      return copy.statusApproved;
    case "PAID":
      return copy.statusPaid;
    case "REJECTED":
      return copy.statusRejected;
    default:
      return copy.statusPending;
  }
}
