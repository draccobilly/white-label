import type { Metadata } from "next";
import Link from "next/link";
import { notFound, redirect } from "next/navigation";
import { BadgeCheck } from "lucide-react";
import { PublicSiteShell } from "@/components/public/PublicSiteShell";
import { getPublicPageChrome } from "@/lib/public-campaigns";
import { getReceiptAccess } from "@/lib/receipt-access";
import { formatMoney } from "@/lib/utils";
import { withPublicPrefix } from "@/lib/public-site-url";

export const dynamic = "force-dynamic";

export const metadata: Metadata = {
  title: "Donation receipt",
  description: "Secure receipt for a verified donation.",
};

export default async function ReceiptPage({
  searchParams,
}: {
  searchParams: Promise<{ token?: string }>;
}) {
  const query = await searchParams;
  if (!query.token || query.token.length > 2000) notFound();
  const [access, chrome] = await Promise.all([
    getReceiptAccess(query.token),
    getPublicPageChrome().catch(() => null),
  ]);
  if (!access) notFound();
  if (!access.available) {
    redirect(
      withPublicPrefix(
        chrome?.pathPrefix,
        `/gerenating-receipt?token=${encodeURIComponent(access.token)}`,
      ),
    );
  }

  const sale = access.sale;
  const paidDate = sale.paidAt ?? sale.createdAt;
  const receiptNumber = `RCPT-${paidDate
    .toISOString()
    .slice(0, 10)
    .replaceAll("-", "")}-${sale.id.slice(0, 6).toUpperCase()}`;

  const inner = (
    <main className="thanks-shell">
      <div className="thanks-card">
        <div className="thanks-hero">
          <span className="thanks-success-icon">
            <BadgeCheck size={48} aria-hidden />
          </span>
          <h1>Donation receipt</h1>
          <p>
            Secure payment record for your contribution to{" "}
            <strong>{sale.campaign.title}</strong>.
          </p>
        </div>
        <section className="thanks-receipt">
          <div className="thanks-receipt-head">
            <span>Receipt</span>
            <strong>
              <BadgeCheck size={15} aria-hidden />
              Verified
            </strong>
          </div>
          <dl>
            <div>
              <dt>Receipt no.</dt>
              <dd>{receiptNumber}</dd>
            </div>
            <div>
              <dt>Date</dt>
              <dd>
                {paidDate.toLocaleDateString("en-US", {
                  month: "short",
                  day: "numeric",
                  year: "numeric",
                })}
              </dd>
            </div>
            <div>
              <dt>Donor</dt>
              <dd>{sale.customerName}</dd>
            </div>
            <div>
              <dt>Tracking code</dt>
              <dd>{sale.trackingCode ?? "Not assigned"}</dd>
            </div>
            <div className="thanks-receipt-total">
              <dt>Total</dt>
              <dd>{formatMoney(sale.amount, sale.currency)}</dd>
            </div>
          </dl>
        </section>
        <p className="receipt-wait-disclaimer">
          {chrome?.institutional
            ? "This is your official donation record from this organization."
            : "This receipt is generated by our team. A supporting PDF may be sent separately within 3 business days."}
        </p>
        <Link
          className="secondary-button thanks-track-button"
          href={
            sale.trackingCode
              ? `/track-your-donation?code=${encodeURIComponent(sale.trackingCode)}`
              : "/track-your-donation"
          }
        >
          Track your donation
        </Link>
      </div>
    </main>
  );

  if (chrome) {
    return <PublicSiteShell chrome={chrome}>{inner}</PublicSiteShell>;
  }
  return inner;
}
