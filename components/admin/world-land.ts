export const HOLES: Ring[] = [BLACK_SEA, CASPIAN];

type Bounds = { minX: number; maxX: number; minY: number; maxY: number };

function bounds(ring: Ring): Bounds {
  let minX = Infinity;
  let maxX = -Infinity;
  let minY = Infinity;
  let maxY = -Infinity;
  for (const [x, y] of ring) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return { minX, maxX, minY, maxY };
}

function inside(ring: Ring, x: number, y: number) {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

const LAND_BOUNDS = LAND.map(bounds);
const HOLE_BOUNDS = HOLES.map(bounds);

export function isLand(lng: number, lat: number) {
  for (let i = 0; i < HOLES.length; i += 1) {
    const b = HOLE_BOUNDS[i];
    if (lng >= b.minX && lng <= b.maxX && lat >= b.minY && lat <= b.maxY && inside(HOLES[i], lng, lat)) return false;
  }
  for (let i = 0; i < LAND.length; i += 1) {
    const b = LAND_BOUNDS[i];
    if (lng >= b.minX && lng <= b.maxX && lat >= b.minY && lat <= b.maxY && inside(LAND[i], lng, lat)) return true;
  }
  return false;
}

/**
 * Evenly spaced points over the land, as [lat, lng] pairs in degrees. The
 * longitude step widens toward the poles so dots keep the same distance on
 * the sphere.
 */
export function landDots(stepDegrees = 2): Float32Array {
  const out: number[] = [];
  for (let lat = -84; lat <= 84; lat += stepDegrees) {
    const stretch = Math.max(0.2, Math.cos((lat * Math.PI) / 180));
    const step = stepDegrees / stretch;
    const offset = ((lat / stepDegrees) % 2 ? step / 2 : 0) % step;
    for (let lng = -180 + offset; lng < 180; lng += step) {
      if (isLand(lng, lat)) out.push(lat, lng);
    }
  }
  return Float32Array.from(out);
}
